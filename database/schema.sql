CREATE TABLE entrepots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    adresse TEXT,
    type VARCHAR(50) NOT NULL
        CHECK (type IN ('SHOWROOM', 'DEPOT', 'ATELIER_SAV'))
);

CREATE TABLE produits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_modele VARCHAR(100) NOT NULL UNIQUE,
    marque VARCHAR(100) NOT NULL,
    categorie VARCHAR(100),
    designation VARCHAR(255) NOT NULL,
    prix_achat_ht NUMERIC(12, 3)
        CHECK (prix_achat_ht IS NULL OR prix_achat_ht >= 0),
    prix_vente_ttc NUMERIC(12, 3) NOT NULL
        CHECK (prix_vente_ttc >= 0),
    duree_garantie_mois INTEGER NOT NULL DEFAULT 12
        CHECK (duree_garantie_mois >= 0),
    seuil_alerte INTEGER NOT NULL DEFAULT 5
        CHECK (seuil_alerte >= 0)
);

CREATE TABLE unites_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id BIGINT NOT NULL REFERENCES produits(id),
    entrepot_id BIGINT NOT NULL REFERENCES entrepots(id),
    numero_serie VARCHAR(150) NOT NULL UNIQUE,
    statut VARCHAR(50) NOT NULL DEFAULT 'EN_STOCK'
        CHECK (statut IN ('EN_STOCK', 'VENDU', 'EN_SAV', 'DEFECTUEUX')),
    date_entree TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE factures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_facture VARCHAR(50) NOT NULL UNIQUE,
    client_nom VARCHAR(150) NOT NULL,
    client_telephone VARCHAR(50),
    matricule_fiscal VARCHAR(100),
    montant_total_ttc NUMERIC(12, 3) NOT NULL
        CHECK (montant_total_ttc >= 0),
    statut_paiement VARCHAR(50) NOT NULL DEFAULT 'IMPAYEE'
        CHECK (statut_paiement IN ('PAYEE', 'PARTIELLE', 'IMPAYEE')),
    date_facture TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE lignes_facture (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facture_id BIGINT NOT NULL REFERENCES factures(id),
    unite_stock_id BIGINT NOT NULL UNIQUE REFERENCES unites_stock(id),
    prix_unitaire_ttc NUMERIC(12, 3) NOT NULL
        CHECK (prix_unitaire_ttc >= 0)
);

CREATE TABLE paiements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facture_id BIGINT NOT NULL REFERENCES factures(id),
    montant NUMERIC(12, 3) NOT NULL CHECK (montant > 0),
    mode VARCHAR(50) NOT NULL
        CHECK (mode IN ('ESPECES', 'CARTE', 'VIREMENT', 'CHEQUE', 'AUTRE')),
    date_paiement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dossiers_sav (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unite_stock_id BIGINT NOT NULL REFERENCES unites_stock(id),
    description_panne TEXT NOT NULL,
    sous_garantie BOOLEAN NOT NULL,
    statut VARCHAR(50) NOT NULL DEFAULT 'OUVERT'
        CHECK (statut IN ('OUVERT', 'EN_REPARATION', 'PRET', 'CLOTURE')),
    cout_reparation NUMERIC(12, 3) NOT NULL DEFAULT 0
        CHECK (cout_reparation >= 0),
    date_ouverture TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_unites_stock_statut_entrepot
    ON unites_stock (statut, entrepot_id);
CREATE INDEX idx_unites_stock_produit_statut
    ON unites_stock (produit_id, statut);
CREATE INDEX idx_factures_date
    ON factures (date_facture DESC);
CREATE INDEX idx_paiements_facture
    ON paiements (facture_id);
CREATE INDEX idx_dossiers_sav_statut
    ON dossiers_sav (statut);
